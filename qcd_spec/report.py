"""Aggregate spec_run results (results/*.json) into results/REPORT_TABLES.md and results/figs/*.png.
Mean +- std over seeds. Retention = K_Z(test) / K_X(test) with K_X from the raw pipeline with the SAME
likelihood family and seed (and the spec's version K_Z(test) / K_X(val) alongside)."""
import json
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

import os
RES = Path(os.environ.get('QCD_RES', Path(__file__).resolve().parent / 'results'))
FIG = RES / 'figs'
FAM = {'tf': ('Causal transformer', '#2f6db5'), 'gru': ('GRU', '#d0603a'), 'tcn': ('TCN', '#3a9b6b'),
       'lin': ('Linear AR(4)', '#7a6bb8')}
INK, MUTED, GRID = '#222222', '#6b6b6b', '#dddddd'
plt.rcParams.update({'font.size': 10, 'axes.edgecolor': '#bbbbbb', 'axes.grid': True, 'grid.color': GRID,
                     'axes.spines.top': False, 'axes.spines.right': False, 'text.color': INK,
                     'axes.labelcolor': INK, 'xtick.color': MUTED, 'ytick.color': MUTED})


def load():
    R = []
    for p in sorted(RES.glob('*.json')):
        m = json.loads(p.read_text())
        if 'tag' in m:
            R.append(m)
    return R


def ms(v, f='{:.3f}'):
    v = [x for x in v if x is not None and np.isfinite(x)]
    if not v:
        return 'n/a'
    return (f + ' ± ' + f).format(np.mean(v), np.std(v)) if len(v) > 1 else f.format(v[0])


def main():
    FIG.mkdir(parents=True, exist_ok=True)
    R = load()
    raw = {(m['args']['q'], m['args']['seed']): m for m in R if m['args']['pipeline'] == 'raw'}
    cae = [m for m in R if m['args']['pipeline'] == 'cae']
    L = ['# Spec run #1 results (auto-generated by report.py)', '',
         'Units: K, E[s] in nats/step; ADD in seconds (1 sample = 0.25 s); FA, DR, FA_pre as fractions of '
         'trajectories. h is recalibrated for every run on val_normal (order statistic, alpha = 0.05).', '']
    # ---------------- raw
    L += ['## Raw pipeline (detectability ceiling)', '',
          '| q family | seeds | K_test | signs ok | E0[s] | margin | FA test_normal | DR | FA_pre | miss | '
          'ADD mean (s) | ADD median (s) |', '|---|---|---|---|---|---|---|---|---|---|---|---|']
    for q in FAM:
        g = [m for (qq, _), m in raw.items() if qq == q]
        if not g:
            continue
        L.append(f"| {FAM[q][0]} | {len(g)} | {ms([m['test']['K'] for m in g])} | "
                 f"{sum(m['test']['signs_ok'] for m in g)}/{len(g)} | {ms([m['test']['E0s'] for m in g])} | "
                 f"{ms([m['test']['margin0'] for m in g])} | {ms([m['FA_test_normal'] for m in g])} | "
                 f"{ms([m['detect']['DR'] for m in g])} | {ms([m['detect']['FA_pre'] for m in g])} | "
                 f"{ms([m['detect']['miss'] for m in g])} | {ms([m['detect']['ADD_mean_s'] for m in g], '{:.1f}')} | "
                 f"{ms([m['detect']['ADD_median_s'] for m in g], '{:.1f}')} |")
    # ---------------- cae
    L += ['', '## Compressed pipelines (k = 8; lambda = 0 is the unaware autoencoder)', '',
          '| enc = q | lambda | seeds | D test normal | D test abnormal | K_test | retention K_Z/K_X | signs ok | '
          'E0[s] | FA test_normal | DR | FA_pre | ADD mean (s) | ADD median (s) |',
          '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|']
    agg = {}
    for f in ('tf', 'gru', 'tcn'):
        for lam in (0.0, 0.25, 0.5, 0.75, 1.0):
            g = [m for m in cae if m['args']['enc'] == f and abs(m['args']['lam'] - lam) < 1e-9]
            if not g:
                continue
            ret = []
            for m in g:
                r = raw.get((f, m['args']['seed']))
                if r is not None and r['test']['K'] > 0:
                    ret.append(m['test']['K'] / r['test']['K'])
            agg[(f, lam)] = dict(D=[m['D_test_normal'] for m in g], Da=[m['D_test_abnormal'] for m in g],
                                 add=[m['detect']['ADD_median_s'] for m in g], ret=ret,
                                 dr=[m['detect']['DR'] for m in g])
            L.append(f"| {FAM[f][0]} | {lam:g} | {len(g)} | {ms([m['D_test_normal'] for m in g])} | "
                     f"{ms([m['D_test_abnormal'] for m in g])} | {ms([m['test']['K'] for m in g])} | {ms(ret)} | "
                     f"{sum(m['test']['signs_ok'] for m in g)}/{len(g)} | {ms([m['test']['E0s'] for m in g])} | "
                     f"{ms([m['FA_test_normal'] for m in g])} | {ms([m['detect']['DR'] for m in g])} | "
                     f"{ms([m['detect']['FA_pre'] for m in g])} | "
                     f"{ms([m['detect']['ADD_mean_s'] for m in g], '{:.1f}')} | "
                     f"{ms([m['detect']['ADD_median_s'] for m in g], '{:.1f}')} |")
    # ---------------- per-type detection rate, transformer family, seed-mean
    types = sorted({t for m in R for t in m.get('detect_per_type', {})})
    if types:
        cols = [('raw', 'tf', None)] + [('cae', 'tf', lam) for lam in (0.0, 0.5, 1.0)]
        L += ['', '## Detection rate per anomaly type (transformer family, mean over seeds)', '',
              '| type | raw | unaware (lambda 0) | lambda 0.5 | lambda 1 |', '|---|---|---|---|---|']
        for t in types:
            cells = []
            for pipe, f, lam in cols:
                g = [m for m in R if m['args']['pipeline'] == pipe and m['args']['q'] == f
                     and (lam is None or abs(m['args']['lam'] - lam) < 1e-9)]
                v = [m['detect_per_type'][t]['DR'] for m in g if t in m['detect_per_type']]
                cells.append(f'{np.mean(v):.2f}' if v else 'n/a')
            L.append(f'| {t} | ' + ' | '.join(cells) + ' |')
    (RES / 'REPORT_TABLES.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
    print('\n'.join(L))

    # ---------------- figure 1: distortion-delay frontier
    fig, ax = plt.subplots(figsize=(6.4, 4.2))
    for f in ('tf', 'gru', 'tcn'):
        pts = [(lam, np.mean(v['D']), np.nanmean([a for a in v['add'] if a is not None] or [np.nan]))
               for (ff, lam), v in sorted(agg.items()) if ff == f]
        if not pts:
            continue
        lam, d, a = zip(*pts)
        ax.plot(d, a, '-o', color=FAM[f][1], lw=2, ms=6, label=FAM[f][0])
        for l_, d_, a_ in pts:
            ax.annotate(f'λ={l_:g}', (d_, a_), textcoords='offset points', xytext=(5, 4), fontsize=8, color=MUTED)
    for q in ('tf', 'gru', 'tcn'):
        g = [m['detect']['ADD_median_s'] for (qq, _), m in raw.items() if qq == q and m['detect']['ADD_median_s']]
        if g:
            ax.axhline(np.mean(g), color=FAM[q][1], ls=':', lw=1.2)
    ax.set_xlabel('Distortion D̄ on test_normal (MSE / σ²_X)')
    ax.set_ylabel('Median detection delay (s)')
    ax.set_title('Distortion–delay frontier (dotted: raw ceiling per family)', fontsize=10)
    ax.legend(frameon=False, fontsize=9)
    fig.tight_layout()
    fig.savefig(FIG / 'frontier.png', dpi=150)
    plt.close(fig)

    # ---------------- figure 2: retention vs lambda
    fig, ax = plt.subplots(figsize=(6.0, 3.8))
    for f in ('tf', 'gru', 'tcn'):
        pts = [(lam, np.mean(v['ret']), np.std(v['ret'])) for (ff, lam), v in sorted(agg.items())
               if ff == f and v['ret']]
        if pts:
            lam, r, s = zip(*pts)
            ax.errorbar(lam, r, yerr=s, fmt='-o', color=FAM[f][1], lw=2, ms=6, capsize=3, label=FAM[f][0])
    ax.set_xlabel('λ (0 = unaware autoencoder)')
    ax.set_ylabel('Retention K̂_Z / K̂_X')
    ax.legend(frameon=False, fontsize=9)
    fig.tight_layout()
    fig.savefig(FIG / 'retention.png', dpi=150)
    plt.close(fig)

    # ---------------- figure 3: post-change drift curves (val_change), transformer family, seed 0
    fig, ax = plt.subplots(figsize=(6.4, 3.8))
    sel = [('raw', None, 'Raw', '#444444')] + [('cae', lam, f'λ={lam:g}', c) for lam, c in
                                               ((0.0, '#9bb7dd'), (0.5, '#4f86c6'), (1.0, '#1d4e8f'))]
    for pipe, lam, lab, c in sel:
        g = [m for m in R if m['args']['pipeline'] == pipe and m['args']['q'] == 'tf' and m['args']['seed'] == 0
             and (lam is None or abs(m['args']['lam'] - lam) < 1e-9)]
        if g:
            cur = g[0]['drift_curve_val_change']
            x = np.array([int(k) for k in cur]) / 4.0
            y = np.array(list(cur.values()))
            o = np.argsort(x)
            yy = np.sign(y[o]) * np.log10(1 + np.abs(y[o]))
            ax.plot(x[o], yy, '-', color=c, lw=2, label=lab)
    ax.axvline(0, color=MUTED, lw=1)
    ax.axvline(32, color=MUTED, lw=1, ls=':')
    ax.set_xlabel('Seconds since change (dotted: context m = 32 s)')
    ax.set_ylabel('E[s_t | t − ν]  (sign · log10(1+|s|), nats)')
    ax.set_title('Post-change drift on val_change (transformer, seed 0)', fontsize=10)
    ax.legend(frameon=False, fontsize=9)
    fig.tight_layout()
    fig.savefig(FIG / 'drift_curves.png', dpi=150)
    plt.close(fig)


if __name__ == '__main__':
    main()

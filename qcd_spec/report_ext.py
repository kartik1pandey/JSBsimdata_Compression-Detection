"""Summary of the extra experiments (run_ext.sh): bit budget, latent size k, encoder x density pairing, decoder.
Reads results/ext/*.json, results/ext/quant/*.json and, for the k = 8 / conv-decoder / matched-pair reference,
the main-grid seed-0 results in results/. Writes results/ext/EXT_TABLES.md and docs/figs/ext_*.png.
Seed 0 only: single-run numbers, no error bars."""
import json
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

HERE = Path(__file__).resolve().parent
MAIN, EXT = HERE / 'results', HERE / 'results' / 'ext'
FIG = HERE / 'docs' / 'figs'
FAM = {'tf': ('Transformer', '#2f6db5'), 'gru': ('GRU', '#d0603a'), 'tcn': ('TCN', '#3a9b6b'),
       'lin': ('Linear AR(4)', '#7a6bb8')}
MUTED = '#6b6b6b'
RAW_RATE = 297 * 32 * 4
plt.rcParams.update({'font.size': 9, 'axes.edgecolor': '#bbbbbb', 'axes.grid': True, 'grid.color': '#e4e4e4',
                     'axes.spines.top': False, 'axes.spines.right': False, 'xtick.color': MUTED,
                     'ytick.color': MUTED})


def jl(p):
    return json.loads(p.read_text())


def cae_runs():
    R = []
    for d in (MAIN, EXT):
        for p in d.glob('cae_*_s0*.json'):
            m = jl(p)
            m['args'].setdefault('dec', 'conv')
            R.append(m)
    return R


def find(R, enc, q, k, lam, dec='conv'):
    for m in R:
        a = m['args']
        if (a['enc'], a['q'], a['k'], a['dec']) == (enc, q, k, dec) and abs(a['lam'] - lam) < 1e-9:
            return m
    return None


RAWK = {}
RAWM = {}
for p in MAIN.glob('raw_q*_s0.json'):
    m = jl(p)
    RAWK[m['args']['q']] = m['test']['K']
    RAWM[m['args']['q']] = m


def ret(m):
    return m['test']['K'] / RAWK[m['args']['q']] if m['args']['q'] in RAWK else np.nan


def f1(v, f='{:.2f}'):
    return 'n/a' if v is None or (isinstance(v, float) and not np.isfinite(v)) else f.format(v)


def row(m, extra=()):
    d = m['detect']
    return ('| ' + ' | '.join(list(extra) + [f1(m.get('D_test_normal'), '{:.3f}'), f1(m['test']['K'], '{:.3g}'),
            f1(ret(m), '{:.3f}'), 'yes' if m['test']['signs_ok'] else '**no**', f1(m['test']['E0s']),
            f1(100 * m['FA_test_normal'], '{:.1f}%'), f1(100 * d['DR'], '{:.0f}%'),
            f1(d['ADD_median_s'], '{:.0f}')]) + ' |')


HDR = 'D̄ normal | K | retention | signs | E0[s] | FA normal | detected | median delay (s)'


def main():
    FIG.mkdir(parents=True, exist_ok=True)
    R = cae_runs()
    L = ['# Extra experiments, seed 0 (auto-generated by report_ext.py)', '',
         'Single seed, full schedule (10/10/15/10 epochs). Retention = K_code / K_raw for the same density family. '
         f'Raw link rate for reference: 297 channels x 32 bit x 4 Hz = {RAW_RATE:,} bit/s.', '']

    # ---------------------------------------------------------------- A bit budget
    Q = [jl(p) for p in sorted((EXT / 'quant').glob('*.json'))] if (EXT / 'quant').exists() else []
    L += ['## A. Bit budget (k = 8 code quantised to b bits per number)', '',
          '| model | λ | b | receiver | bit/s | ' + HDR.replace('retention | ', 'retention | ') + ' |',
          '|' + '---|' * 13]
    tags = sorted({q['tag'] for q in Q})
    for t in tags:
        for qq in sorted([q for q in Q if q['tag'] == t], key=lambda q: (q['receiver'], q['bits'])):
            a = qq['args']
            qq.setdefault('args', a)
            L.append(row(qq, (FAM[a['enc']][0], f"{a['lam']:g}", str(qq['bits']), qq['receiver'],
                              f"{qq['rate_bit_s']:,}")))
        base = find(R, *(lambda a: (a['enc'], a['q'], a['k'], a['lam']))(jl(MAIN / f'{t}.json')['args']))
        if base:
            a = base['args']
            L.append(row(base, (FAM[a['enc']][0], f"{a['lam']:g}", '32 (float)', 'trained', f'{8 * 32 * 4:,}')))
    if Q:
        fig, axs = plt.subplots(1, 3, figsize=(13, 3.9))
        for t in tags:
            a = jl(MAIN / f'{t}.json')['args']
            col = FAM[a['enc']][1]
            ls = '-' if a['lam'] > 0 else ':'
            base = jl(MAIN / f'{t}.json')
            for recv, mk in (('refit', 'o'),):
                pts = sorted([q for q in Q if q['tag'] == t and q['receiver'] == recv], key=lambda q: q['bits'])
                if not pts:
                    continue
                x = [q['rate_bit_s'] for q in pts] + [8 * 32 * 4]
                ys = [[100 * q['detect']['DR'] for q in pts] + [100 * base['detect']['DR']],
                      [q['detect']['ADD_median_s'] or np.nan for q in pts] + [base['detect']['ADD_median_s']],
                      [100 * q['FA_test_normal'] for q in pts] + [100 * base['FA_test_normal']]]
                for ax, y in zip(axs, ys):
                    ax.plot(x, y, ls, marker=mk, color=col, lw=1.8, ms=5,
                            label=f"{FAM[a['enc']][0]}, λ = {a['lam']:g}")
                for xx, b in zip(x, [q['bits'] for q in pts] + ['f32']):
                    axs[0].annotate(str(b), (xx, ys[0][x.index(xx)]), textcoords='offset points', xytext=(0, 5),
                                    fontsize=7, color=MUTED, ha='center')
        for ax, yl in zip(axs, ('faults detected (%)', 'median delay (s)', 'false alarms on normal flights (%)')):
            ax.set_xscale('log', base=2)
            ax.set_xlabel('link rate (bit/s) = 8 numbers × b bits × 4 Hz')
            ax.set_ylabel(yl)
        axs[2].axhline(5, color='#d0603a', lw=1, ls='--')
        for q in ('tf', 'gru'):
            if q in RAWM:
                axs[0].axhline(100 * RAWM[q]['detect']['DR'], color=FAM[q][1], lw=0.8, ls='--')
        axs[0].legend(frameon=False, fontsize=8)
        fig.suptitle('Bit budget: detection vs link rate (q0/q1 refit on the quantised code; labels = bits per '
                     'number; dashed = raw data)', x=0.01, ha='left', fontsize=10)
        fig.tight_layout(rect=(0, 0, 1, 0.93))
        fig.savefig(FIG / 'ext_bits.png', dpi=140)
        plt.close(fig)

    # ---------------------------------------------------------------- B latent size
    L += ['', '## B. Latent size k (code = k float numbers per step)', '',
          '| model | λ | k | float32 bit/s | ' + HDR + ' |', '|' + '---|' * 12]
    ks = (2, 4, 8, 16, 32, 64, 128)
    fig, axs = plt.subplots(1, 4, figsize=(15, 3.8))
    for f in ('tf', 'gru'):
        for lam in (0.0, 0.25):
            pts = [(k, find(R, f, f, k, lam)) for k in ks]
            pts = [(k, m) for k, m in pts if m]
            for k, m in pts:
                L.append(row(m, (FAM[f][0], f'{lam:g}', str(k), f'{k * 32 * 4:,}')))
            if len(pts) < 2:
                continue
            x = [k for k, _ in pts]
            ys = [[m['D_test_normal'] for _, m in pts], [max(ret(m), 1e-5) for _, m in pts],
                  [100 * m['detect']['DR'] for _, m in pts], [m['detect']['ADD_median_s'] or np.nan for _, m in pts]]
            ok = [m['test']['signs_ok'] for _, m in pts]
            for ax, y in zip(axs, ys):
                ax.plot(x, y, '-' if lam > 0 else ':', color=FAM[f][1], lw=1.8,
                        label=f'{FAM[f][0]}, λ = {lam:g}')
                for xx, yy, o in zip(x, y, ok):            # filled = passes sign check, hollow = fails
                    ax.plot([xx], [yy], 'o', ms=6, color=FAM[f][1], mfc=FAM[f][1] if o else 'white', mew=1.6)
    for ax, yl in zip(axs, ('D̄ reconstruction error', 'retention K_code / K_raw', 'faults detected (%)',
                            'median delay (s)')):
        ax.set_xscale('log', base=2)
        ax.set_xticks(ks, [str(k) for k in ks])
        ax.set_xlabel('latent size k')
        ax.set_ylabel(yl)
    axs[1].set_yscale('log')
    axs[1].axhline(1, color=MUTED, lw=1, ls='--')
    axs[0].legend(frameon=False, fontsize=8)
    fig.suptitle('Latent size: dotted = plain autoencoder (λ = 0), solid = task-aware (λ = 0.25); '
                 'hollow marker = fails the sign check (not valid)', x=0.01,
                 ha='left', fontsize=10)
    fig.tight_layout(rect=(0, 0, 1, 0.93))
    fig.savefig(FIG / 'ext_latent_k.png', dpi=140)
    plt.close(fig)

    # ---------------------------------------------------------------- C pairing
    L += ['', '## C. Encoder family x density family (k = 8)', '',
          '| encoder | q0/q1 | λ | ' + HDR + ' |', '|' + '---|' * 11]
    encs, qs = ('tf', 'gru'), ('tf', 'gru', 'tcn', 'lin')
    fig, axs = plt.subplots(1, 2, figsize=(11, 3.4))
    for ax, lam in zip(axs, (0.0, 0.25)):
        M = np.full((len(encs), len(qs)), np.nan)
        for i, e in enumerate(encs):
            for j, q in enumerate(qs):
                m = find(R, e, q, 8, lam)
                if m:
                    L.append(row(m, (FAM[e][0], FAM[q][0], f'{lam:g}')))
                    M[i, j] = 100 * m['detect']['DR']
                    ok = m['test']['signs_ok']
                    ax.text(j, i, f"{M[i, j]:.0f}%\n{'' if ok else 'signs ✗'}", ha='center', va='center',
                            fontsize=9, color='white' if M[i, j] > 30 else '#222222')
        ax.imshow(M, cmap='Blues', vmin=0, vmax=60, aspect='auto')
        ax.set_xticks(range(len(qs)), [FAM[q][0] for q in qs])
        ax.set_yticks(range(len(encs)), [FAM[e][0] + ' enc.' for e in encs])
        ax.set_xlabel('density model q0 / q1')
        ax.set_title(f'faults detected, λ = {lam:g}', loc='left', fontsize=10)
        ax.grid(False)
    fig.suptitle('Which encoder goes with which density model (empty = not run yet)', x=0.01, ha='left',
                 fontsize=10)
    fig.tight_layout(rect=(0, 0, 1, 0.92))
    fig.savefig(FIG / 'ext_pairing.png', dpi=140)
    plt.close(fig)

    # ---------------------------------------------------------------- D decoder
    L += ['', '## D. Decoder family (k = 8; conv is the default used everywhere else)', '',
          '| model | decoder | λ | ' + HDR + ' |', '|' + '---|' * 11]
    decs = ('conv', 'mlp', 'bigru')
    fig, axs = plt.subplots(1, 2, figsize=(11, 3.6))
    w = 0.18
    i = 0
    labels = []
    for f in ('tf', 'gru'):
        for lam in (0.0, 0.25):
            ms = [find(R, f, f, 8, lam, dec) for dec in decs]
            for dec, m in zip(decs, ms):
                if m:
                    L.append(row(m, (FAM[f][0], dec, f'{lam:g}')))
            x = np.arange(len(decs)) + (i - 1.5) * w
            axs[0].bar(x, [m['D_test_normal'] if m else 0 for m in ms], w, color=FAM[f][1],
                       alpha=1 if lam > 0 else 0.45)
            axs[1].bar(x, [100 * m['detect']['DR'] if m else 0 for m in ms], w, color=FAM[f][1],
                       alpha=1 if lam > 0 else 0.45, label=f'{FAM[f][0]}, λ = {lam:g}')
            i += 1
    for ax, yl in zip(axs, ('D̄ reconstruction error', 'faults detected (%)')):
        ax.set_xticks(range(len(decs)), ['conv (default)', 'per-step MLP', 'bidirectional GRU'])
        ax.set_ylabel(yl)
    axs[1].legend(frameon=False, fontsize=8)
    fig.suptitle('Decoder family (pale = λ 0, solid = λ 0.25; zero-height = not run yet)', x=0.01, ha='left',
                 fontsize=10)
    fig.tight_layout(rect=(0, 0, 1, 0.92))
    fig.savefig(FIG / 'ext_decoder.png', dpi=140)
    plt.close(fig)

    (EXT / 'EXT_TABLES.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
    print('\n'.join(L))


if __name__ == '__main__':
    main()

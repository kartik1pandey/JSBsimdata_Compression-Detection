def jl(p):
    return json.loads(p.read_text())


def metrics(m):
    d, t = m['detect'], m['test']
    add = d['ADD_median_s']
    return dict(DR=d['DR'], ADD=np.nan if add is None else add, ADDmean=np.nan if d['ADD_mean_s'] is None
                else d['ADD_mean_s'], FA=m['FA_test_normal'], FApre=d['FA_pre'], valid=bool(t['signs_ok']),
                K=t['K'], E0=t['E0s'], E1=t['E1s'], Dn=m.get('D_test_normal', np.nan))


def load(dirs, machine):
    out = []
    for d in dirs:
        for p in sorted(d.glob('*.json')):
            m = jl(p)
            if 'tag' not in m or 'detect' not in m:
                continue
            a = dict(m['args'])
            a.setdefault('dec', 'conv')
            a.setdefault('head', 'gauss')
            a.setdefault('enc_out', 'ln')
            out.append(dict(a=a, x=metrics(m), machine=machine, tag=m['tag'], log=m.get('log', []),
                            config=m.get('config'), train_s=m.get('train_s')))
    return out


STD = [r for mach, ds in STD_DIRS.items() for r in load(ds, mach)]
LONG = load([R / 'long'], 'server')
MOG = load([R / 'mog'], 'server')
REPRO = load([R / 'repro'], 'server')
QUANT = []
for mach, d in (('laptop', R / 'ext' / 'quant'), ('server', R / 'srv' / 'quant')):
    for p in sorted(d.glob('*.json')) if d.exists() else []:
        m = jl(p)
        QUANT.append(dict(a=m['args'], b=m['bits'], recv=m['receiver'], rate=m['rate_bit_s'], x=metrics(m),
                          machine=mach))


def sel(runs, **kw):
    o = []
    for r in runs:
        a = r['a']
        if all((abs(a.get(k, -9) - v) < 1e-9) if isinstance(v, float) else a.get(k) == v for k, v in kw.items()):
            o.append(r)
    return o


def agg(rs, key):
    v = np.array([r['x'][key] for r in rs], float)
    f = v[np.isfinite(v)]
    return (f.mean() if len(f) else np.nan, f.std() if len(f) > 1 else 0.0, len(v))


RAWK = defaultdict(list)
for r in sel(STD, pipeline='raw'):
    RAWK[(r['a']['q'], r['a']['seed'])] = r['x']['K']


def retention(r):
    k = RAWK.get((r['a']['q'], r['a']['seed']))
    return r['x']['K'] / k if k else np.nan


def cell(rs, key, fmt='{:.0f}', scale=1.0):
    if not rs:
        return '—'
    m, s, n = agg(rs, key)
    if not np.isfinite(m):
        return 'n/a'
    return (fmt.format(m * scale) + (' ± ' + fmt.format(s * scale) if n > 1 else ''))


def vcell(rs):
    return f"{sum(r['x']['valid'] for r in rs)}/{len(rs)}" if rs else '—'


def row(rs):
    return [cell(rs, 'DR', '{:.0f}', 100), cell(rs, 'ADD', '{:.0f}'), cell(rs, 'FA', '{:.1f}', 100), vcell(rs),
            cell(rs, 'Dn', '{:.3f}'), cell(rs, 'E0', '{:.2f}')]


